(* Embeds the Metal kernel sources into an OCaml module.
   Invoked by the build as: gen_shaders.exe a.metal b.metal ... > shaders.ml

   The DS4 Metal backend reads each kernel from a file at engine-open time
   (honouring per-kernel DS4_METAL_<NAME>_SOURCE env overrides).  Embedding the
   sources here, then materialising them to a cache dir at runtime, makes the
   built binary relocatable instead of cwd-dependent. *)

let () =
  let buf = Buffer.create 65536 in
  Buffer.add_string buf
    "(* Generated by gen/gen_shaders.ml. Do not edit. *)\n\n";
  Buffer.add_string buf "let sources : (string * string) list = [\n";
  for i = 1 to Array.length Sys.argv - 1 do
    let path = Sys.argv.(i) in
    if Filename.check_suffix path ".metal" then begin
      let name = Filename.remove_extension (Filename.basename path) in
      let ic = open_in_bin path in
      let len = in_channel_length ic in
      let body = really_input_string ic len in
      close_in ic;
      (* %S emits a correctly escaped OCaml string literal. *)
      Buffer.add_string buf (Printf.sprintf "  (%S, %S);\n" name body)
    end
  done;
  Buffer.add_string buf "]\n";
  print_string (Buffer.contents buf)
