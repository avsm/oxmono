let account_otks account =
  O.Account.one_time_keys account
  |> List.map (fun (id, key) ->
      (Ck.Key_id.id id, Ck.Curve25519.Public.to_base64 key))
  |> List.sort compare

let test_rust_fixture () =
  let decoded =
    match
      P.unpickle ~device_id:device ~pickle_key:raw_key rust_fixture_pickle
    with
    | Ok value -> value
    | Error (`Msg message) -> Alcotest.fail message
  in
  Alcotest.(check string)
    "fixture Ed25519" rust_fixture_ed25519
    (Ck.Ed25519.Public.to_base64 (O.Account.ed25519_key decoded.account));
  Alcotest.(check string)
    "fixture Curve25519" rust_fixture_curve25519
    (Ck.Curve25519.Public.to_base64 (O.Account.curve25519_key decoded.account));
  Alcotest.(check (list (pair string string)))
    "fixture one-time keys" rust_fixture_otks
    (account_otks decoded.account);
  Alcotest.(check (list string))
    "published fixture OTK IDs"
    (List.map fst rust_fixture_otks)
    (decoded.published_one_time_keys |> List.map Ck.Key_id.id
   |> List.sort String.compare);
  Alcotest.(check (list string))
    "published fixture fallback ID" [ "AAAAAAAAAAA" ]
    (List.map Ck.Key_id.id decoded.published_fallback_keys);
  let message = "recorded Rust pickle still signs" in
  let signature = O.Account.sign decoded.account message in
  Alcotest.(check bool)
    "expanded fixture key signs" true
    (Ck.Ed25519.Public.verify
       (O.Account.ed25519_key decoded.account)
       ~signature ~data:message)

let test_high_bit_key_id () =
  let original = O.Account.create ~random () in
  O.Account.generate_one_time_keys ~random original 1;
  let pickle = O.Account.to_pickle original in
  let key = List.hd pickle.stored_one_time_keys in
  let high_id = "AAAAAIAAAAA" in
  let account =
    O.Account.of_pickle
      {
        pickle with
        stored_one_time_keys = [ { key with key_id = high_id } ];
        next_key_id = 0x80000001;
      }
  in
  let encoded =
    Result.get_ok (P.pickle ~device_id:device ~pickle_key:raw_key account)
  in
  let decoded =
    Result.get_ok (P.unpickle ~device_id:device ~pickle_key:raw_key encoded)
  in
  Alcotest.(check (list string))
    "u32 ID is zero-extended" [ high_id ]
    (O.Account.one_time_key_ids decoded.account |> List.map Ck.Key_id.id)

let test_roundtrip () =
  let account = O.Account.create ~random () in
  O.Account.generate_one_time_keys ~random account 3;
  O.Account.generate_fallback_key ~random account;
  let value =
    match
      P.pickle
        ~is_published:(fun _ -> true)
        ~device_id:device ~pickle_key:raw_key account
    with
    | Ok x -> x
    | Error (`Msg m) -> Alcotest.fail m
  in
  let d =
    match P.unpickle ~device_id:device ~pickle_key:raw_key value with
    | Ok x -> x
    | Error (`Msg m) -> Alcotest.fail m
  in
  Alcotest.(check string)
    "identity"
    (Ck.Ed25519.Public.to_base64 (O.Account.ed25519_key account))
    (Ck.Ed25519.Public.to_base64 (O.Account.ed25519_key d.account));
  Alcotest.(check int) "otk count" 3 (O.Account.one_time_keys_count d.account);
  Alcotest.(check int)
    "published OTK count" 3
    (List.length d.published_one_time_keys);
  Alcotest.(check int)
    "published fallback count" 1
    (List.length d.published_fallback_keys)

let test_rejects () =
  let account = O.Account.create ~random () in
  let value =
    match P.pickle ~device_id:device ~pickle_key:raw_key account with
    | Ok x -> x
    | Error (`Msg m) -> Alcotest.fail m
  in
  let bad_device = Id.Device_id.of_string_exn "OTHER" in
  let bad s =
    match P.unpickle ~device_id:device ~pickle_key:raw_key s with
    | Ok _ -> false
    | Error _ -> true
  in
  Alcotest.(check bool)
    "wrong key" true
    (match
       P.unpickle ~device_id:device ~pickle_key:(String.make 32 'x') value
     with
    | Ok _ -> false
    | Error _ -> true);
  Alcotest.(check bool)
    "wrong device" true
    (match P.unpickle ~device_id:bad_device ~pickle_key:raw_key value with
    | Ok _ -> false
    | Error _ -> true);
  let tampered =
    String.mapi
      (fun i c -> if i = 3 then Char.chr (Char.code c lxor 1) else c)
      value
  in
  Alcotest.(check bool) "tamper" true (bad tampered);
  Alcotest.(check bool)
    "truncation" true
    (bad (String.sub value 0 (String.length value - 2)))

let test_oracle () =
  match oracle_path () with
  | None -> Printf.printf "SKIP vodozemac oracle not built\n%!"
  | Some path ->
      let ic, oc = Unix.open_process_args path [| path |] in
      let o = { ic; oc } in
      Fun.protect
        ~finally:(fun () -> ignore (Unix.close_process (ic, oc)))
        (fun () ->
          let created =
            call o (cmd "create_account" [ ("one_time_keys", "3") ])
          in
          let account = json_int (field created "account") in
          ignore
            (call o
               (cmd "generate_fallback_key"
                  [ ("account", string_of_int account) ]));
          let picked =
            call o
              (cmd "account_pickle"
                 [
                   ("account", string_of_int account);
                   ("pickle_key", jstring_esc (b64 raw_key));
                   ("device_id", jstring_esc (Id.Device_id.to_string device));
                 ])
          in
          let rust_pickle = json_string (field picked "pickle") in
          let decoded =
            match
              P.unpickle ~device_id:device ~pickle_key:raw_key rust_pickle
            with
            | Ok x -> x
            | Error (`Msg m) -> Alcotest.failf "Rust pickle: %s" m
          in
          let rust_ed = json_string (field created "ed25519") in
          Alcotest.(check string)
            "Rust pickle identity" rust_ed
            (Ck.Ed25519.Public.to_base64
               (O.Account.ed25519_key decoded.account));
          Alcotest.(check int)
            "Rust pickle OTKs" 3
            (O.Account.one_time_keys_count decoded.account);
          let message = "legacy expanded signing" in
          let signature =
            Ck.Signature.to_base64 (O.Account.sign decoded.account message)
          in
          ignore
            (call o
               (cmd "ed25519_verify"
                  [
                    ("key", jstring_esc rust_ed);
                    ("message", jstring_esc message);
                    ("signature", jstring_esc signature);
                  ]));
          let local =
            match
              P.pickle
                ~is_published:(fun _ -> true)
                ~device_id:device ~pickle_key:raw_key decoded.account
            with
            | Ok x -> x
            | Error (`Msg m) -> Alcotest.fail m
          in
          let reply =
            call o
              (cmd "account_from_pickle"
                 [
                   ("pickle", jstring_esc local);
                   ("pickle_key", jstring_esc (b64 raw_key));
                   ("device_id", jstring_esc (Id.Device_id.to_string device));
                 ])
          in
          Alcotest.(check string)
            "OCaml pickle identity" rust_ed
            (json_string (field reply "ed25519"));
          let signed =
            call o
              (cmd "account_sign_from_pickle"
                 [
                   ("pickle", jstring_esc local);
                   ("pickle_key", jstring_esc (b64 raw_key));
                   ("device_id", jstring_esc (Id.Device_id.to_string device));
                   ("message", jstring_esc message);
                 ])
          in
          let rust_signature = json_string (field signed "signature") in
          Alcotest.(check string)
            "expanded-key signatures agree" signature rust_signature;
          let rust_signature =
            Result.get_ok (Ck.Signature.of_base64 rust_signature)
          in
          Alcotest.(check bool)
            "OCaml verifies Rust restored signature" true
            (Ck.Ed25519.Public.verify
               (O.Account.ed25519_key decoded.account)
               ~signature:rust_signature ~data:message))

