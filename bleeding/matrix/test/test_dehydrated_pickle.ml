let random =
  R.of_source
    (Eio.Flow.string_source
       (String.init 65536 (fun i -> Char.chr (((i * 71) + 19) land 255))))

let jstring_esc s =
  let b = Buffer.create (String.length s + 2) in
  Buffer.add_char b '"';
  String.iter
    (fun c ->
      match c with
      | '"' -> Buffer.add_string b "\\\""
      | '\\' -> Buffer.add_string b "\\\\"
      | '\n' -> Buffer.add_string b "\\n"
      | c when Char.code c < 0x20 ->
          Buffer.add_string b (Printf.sprintf "\\u%04x" (Char.code c))
      | c -> Buffer.add_char b c)
    s;
  Buffer.add_char b '"';
  Buffer.contents b

let json_map s =
  match
    Jsont_bytesrw.decode_string
      (Matrix_proto.Json.Codec.as_string_map Matrix_proto.Json.Codec.json)
      s
  with
  | Ok x -> x
  | Error e -> Alcotest.fail e

let json_string x =
  match Jsont.Json.decode Matrix_proto.Json.Codec.string x with
  | Ok s -> s
  | Error e -> Alcotest.failf "oracle field was not a string: %s" e

let json_int x =
  match Jsont.Json.decode Matrix_proto.Json.Codec.int x with
  | Ok n -> n
  | Error e -> Alcotest.failf "oracle field was not an integer: %s" e

let field m name =
  match Smap.find_opt name m with
  | Some x -> x
  | None -> Alcotest.failf "oracle response lacks %s" name

let cmd name fields =
  "{" ^ jstring_esc "cmd" ^ ":" ^ jstring_esc name
  ^ (if fields = [] then "" else ",")
  ^ String.concat "," (List.map (fun (k, v) -> jstring_esc k ^ ":" ^ v) fields)
  ^ "}"

type oracle = { ic : in_channel; oc : out_channel }

let oracle_path () =
  match Sys.getenv_opt "VODOZEMAC_ORACLE" with
  | Some p when Sys.file_exists p -> Some p
  | _ ->
      let rel =
        Filename.concat "test"
          (Filename.concat "vodozemac-oracle"
             (Filename.concat "target"
                (Filename.concat "release" "vodozemac-oracle")))
      in
      let rec up dir n =
        if n = 0 then None
        else
          let p = Filename.concat dir rel in
          if Sys.file_exists p then Some p
          else
            let parent = Filename.dirname dir in
            if parent = dir then None else up parent (n - 1)
      in
      up (Sys.getcwd ()) 8

let call o request =
  output_string o.oc request;
  output_char o.oc '\n';
  flush o.oc;
  let response =
    try input_line o.ic with End_of_file -> Alcotest.fail "oracle exited"
  in
  let fields = json_map response in
  match Smap.find_opt "ok" fields with
  | Some x when Jsont.Json.decode Jsont.bool x = Ok true -> fields
  | _ -> Alcotest.failf "oracle error: %s" response

